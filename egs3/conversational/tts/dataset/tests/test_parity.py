"""Golden parity: session builders + frozen planner == retired offline manifests.

The goldens under golden/ were generated by the pre-refactor builders on
committed synthetic corpora (see golden/generate_goldens.py).  Each corpus
test re-runs the NEW builder on the same inputs, plans frozen windows, and
compares windows.to_json output line-by-line against the golden JSONL.
"""

import shutil
from pathlib import Path

from ..builder import SSSDBuilder
from ..candor_builder import CandorBuilder
from ..fisher_builder import FisherBuilder
from ..libritts_builder import LibriTTSBuilder
from ..preprocessing.planner import WindowParams, plan_sessions
from ..preprocessing.sessions import read_session_manifest
from ..preprocessing.windows import to_json
from .golden.generate_goldens import load_golden

_GOLDEN_INPUTS = Path(__file__).resolve().parent / "golden" / "inputs"

# Window params the goldens were built with = dataset/config.yaml values at
# freeze time (identical across SSSD/CANDOR/Fisher).
GOLDEN_PARAMS = WindowParams()  # defaults ARE the ratified values
SEED = 0


def _frozen_json(session_manifest, params=GOLDEN_PARAMS, seed=SEED):
    sessions = read_session_manifest(session_manifest)
    records, _ = plan_sessions(sessions, params=params, seed=seed, epoch=None)
    return [to_json(r) for r in records]


def _run_new_sssd_build(tmp_path):
    """Copy the committed SSSD golden inputs (read-only) into tmp_path and run
    the NEW builder against the copy, mirroring generate_goldens.py's SSSD
    invocation (the same corpus root, base vocab, and seed).

    Running SSSD alone (not chained through a shared recipe dir with the
    other corpora, unlike generate_goldens.py) is faithful here specifically
    because generate_goldens.py builds SSSD FIRST and SSSD reads nothing any
    other builder writes: it produces its own extended vocab from its own
    base_vocab_path, so an isolated build reproduces the same vocab and hence
    the same text normalization. CANDOR/Fisher/LibriTTS run AFTER SSSD in
    generate_goldens.py and normalize against the vocab SSSD wrote, so their
    Task 6-8 parity helpers must NOT copy this isolated pattern -- they need
    to chain through an SSSD-built recipe dir or their goldens will not
    match (wrong charset -> different <OTHER> counts -> different text)."""
    sssd_src = _GOLDEN_INPUTS / "sssd"
    sssd_tmp = tmp_path / "sssd"
    shutil.copytree(sssd_src, sssd_tmp)

    recipe_dir = tmp_path / "recipe"
    SSSDBuilder().build(
        recipe_dir=recipe_dir,
        dataset_root=sssd_tmp / "corpus",
        seed=SEED,
        base_vocab_path=sssd_tmp / "base_vocab.txt",
    )
    return recipe_dir


class TestSSSDParity:
    def test_train_valid_test_bit_parity(self, tmp_path):
        recipe = _run_new_sssd_build(tmp_path)
        for split in ("train", "valid", "test"):
            got = _frozen_json(recipe / "data" / "manifest" / f"sessions_{split}.jsonl")
            assert got == load_golden(f"sssd_{split}")


def _run_new_libritts_build(tmp_path):
    """Mirror generate_goldens.py's LibriTTS invocation exactly: SSSD builds
    FIRST into a shared recipe dir (writing the extended vocab), then the NEW
    LibriTTSBuilder runs against that same recipe dir. LibriTTS normalizes
    transcripts against the vocab SSSD wrote, so an isolated LibriTTS-only
    build (unlike SSSD's own isolated parity helper above -- see its
    docstring) would normalize against a DIFFERENT charset and silently
    diverge from the golden. See generate_goldens.py's ``generate()``, which
    runs SSSDBuilder().build(...) before LibriTTSBuilder().build(...) into
    the same recipe_dir for exactly this reason."""
    sssd_src = _GOLDEN_INPUTS / "sssd"
    sssd_tmp = tmp_path / "sssd"
    shutil.copytree(sssd_src, sssd_tmp)

    libritts_src = _GOLDEN_INPUTS / "libritts"
    libritts_tmp = tmp_path / "libritts"
    shutil.copytree(libritts_src, libritts_tmp)

    recipe_dir = tmp_path / "recipe"
    SSSDBuilder().build(
        recipe_dir=recipe_dir,
        dataset_root=sssd_tmp / "corpus",
        seed=SEED,
        base_vocab_path=sssd_tmp / "base_vocab.txt",
    )
    LibriTTSBuilder().build(
        recipe_dir=recipe_dir, dataset_root=libritts_tmp / "LibriTTS", seed=SEED
    )
    return recipe_dir


class TestLibriTTSParity:
    def test_train_valid_bit_parity(self, tmp_path):
        recipe = _run_new_libritts_build(tmp_path)
        for split in ("train", "valid"):
            got = _frozen_json(
                recipe / "data" / "manifest" / f"sessions_libritts_{split}.jsonl"
            )
